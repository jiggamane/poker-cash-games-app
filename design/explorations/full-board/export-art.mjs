/**
 * The approved drawings, out of the icon board and into the app.
 *
 *   node design/explorations/full-board/export-art.mjs
 *
 * Writes `apps/mobile/src/art/spots.ts`: each place's drawing as an SVG string
 * in both palettes (Fresh Deck on white, and on the ink for the dark theme),
 * its measured outline, and its size at each level by the board's ink rule.
 * The app draws them with `<Spot>`; it never draws one of its own. Re-run when
 * a drawing changes on the icon board, and commit the output with it.
 */
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { spot } from '../icon-system/art.mjs';
import BB from '../icon-system/bboxes.json' with { type: 'json' };
import { PICK } from '../icon-system/picks.mjs';
import { sizeFor } from '../icon-system/fresh-deck.mjs';

const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, '../../../apps/mobile/src/art/spots.ts');
const LEVELS = ['rows', 'sheet', 'home', 'tools'];
const strip = (svg) => svg.replace(/ width="\d+" height="\d+"/, '').replace(' aria-hidden="true"', '');
const entries = Object.entries(PICK).map(([place, key]) => {
  const sizes = Object.fromEntries(LEVELS.map((l) => [l, Math.round(sizeFor(key, l) * 10) / 10]));
  return `  ${JSON.stringify(place)}: {
    light: ${JSON.stringify(strip(spot(key, 'freshDeck', { size: 88, small: false })))},
    dark: ${JSON.stringify(strip(spot(key, 'freshDeckOnInk', { size: 88, small: false })))},
    box: ${JSON.stringify(BB[key])},
    size: ${JSON.stringify(sizes)},
  },`;
});
writeFileSync(out, `/*
 * GENERATED by design/explorations/full-board/export-art.mjs — do not edit.
 *
 * The approved spot drawings (the icon board, 21 November 2026), one per
 * place: an SVG on the viewBox "4 12 88 88" in each palette, the drawing's
 * measured outline [x, y, w, h] in that box, and its size in points at each
 * level by the board's ink rule. \`components/Spot.tsx\` draws them.
 */
export type SpotLevel = ${LEVELS.map((l) => `'${l}'`).join(' | ')};
export interface SpotArt {
  light: string;
  dark: string;
  box: [number, number, number, number];
  size: Record<SpotLevel, number>;
}
export const SPOTS = {
${entries.join('\n')}
} satisfies Record<string, SpotArt>;
export type SpotPlace = keyof typeof SPOTS;
`);
console.log('wrote', out);
